// Builds the icon font from web/icons/fontello.json through the Fontello
// developers API (https://github.com/fontello/fontello#developers-api):
//   1. POST the config to https://fontello.com/ -> session id
//   2. GET  https://fontello.com/<id>/get       -> zip with the font
// Writes, all committed so the app build needs no network:
//   web/public/fonts/icons.woff2     the font
//   web/src/icons/icons.css          @font-face + one .icon-<name> class per glyph
//   web/src/icons/names.ts           IconName union, checked by tsc
// usage: pnpm icons   (after editing web/icons/fontello.json)

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { inflateRawSync } from "node:zlib";
import { z } from "zod";

const CONFIG = "web/icons/fontello.json";

const ConfigSchema = z.object({ glyphs: z.array(z.object({ uid: z.string(), css: z.string(), code: z.number(), src: z.string() })) });

// Minimal zip reader: walks the central directory, inflates the named entries.
function unzip(zip: Buffer, wanted: (name: string) => boolean): Map<string, Buffer> {
  const eocd = zip.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (eocd < 0) throw new Error("not a zip file");
  const count = zip.readUInt16LE(eocd + 10);
  let p = zip.readUInt32LE(eocd + 16);
  const out = new Map<string, Buffer>();
  for (let i = 0; i < count; i++) {
    const method = zip.readUInt16LE(p + 10);
    const size = zip.readUInt32LE(p + 20);
    const nameLen = zip.readUInt16LE(p + 28);
    const extraLen = zip.readUInt16LE(p + 30);
    const commentLen = zip.readUInt16LE(p + 32);
    const local = zip.readUInt32LE(p + 42);
    const name = zip.toString("utf8", p + 46, p + 46 + nameLen);
    p += 46 + nameLen + extraLen + commentLen;
    if (!wanted(name)) continue;
    const start = local + 30 + zip.readUInt16LE(local + 26) + zip.readUInt16LE(local + 28);
    const data = zip.subarray(start, start + size);
    out.set(name, method === 0 ? Buffer.from(data) : inflateRawSync(data));
  }
  return out;
}

const config = await readFile(CONFIG, "utf8");
const { glyphs } = ConfigSchema.parse(JSON.parse(config));

const form = new FormData();
form.append("config", new Blob([config], { type: "application/json" }), "config.json");
const session = await fetch("https://fontello.com/", { method: "POST", body: form });
if (!session.ok) throw new Error(`fontello session: HTTP ${String(session.status)} ${await session.text()}`);
const id = (await session.text()).trim();

const download = await fetch(`https://fontello.com/${id}/get`);
if (!download.ok) throw new Error(`fontello download: HTTP ${String(download.status)}`);
const files = unzip(Buffer.from(await download.arrayBuffer()), (n) => n.endsWith("/font/icons.woff2"));
const woff2 = [...files.values()][0];
if (!woff2) throw new Error("icons.woff2 missing from the fontello zip");

await mkdir("web/public/fonts", { recursive: true });
await mkdir("web/src/icons", { recursive: true });
await writeFile("web/public/fonts/icons.woff2", woff2);

const header = "/* GENERATED by scripts/build-icons.ts from web/icons/fontello.json. Do not edit. */\n";
const css =
  header +
  `@font-face {
  font-family: "icons";
  src: url("/fonts/icons.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.icon {
  font-family: "icons";
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  display: inline-block;
  speak: never;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
` +
  glyphs.map((g) => `.icon-${g.css}::before { content: "\\${g.code.toString(16)}"; }`).join("\n") +
  "\n";
await writeFile("web/src/icons/icons.css", css);

const names =
  header.replace("/*", "//").replace(" */", "") +
  `export const iconNames = [${glyphs.map((g) => JSON.stringify(g.css)).join(", ")}] as const;\n` +
  "export type IconName = (typeof iconNames)[number];\n";
await writeFile("web/src/icons/names.ts", names);

console.log(`icons: ${String(glyphs.length)} glyphs, ${String(woff2.length)} bytes (fontello session ${id})`);
